// Signing: if the AIO_KEYSTORE_* environment variables are set (e.g. from GitHub secrets) builds are signed
// with your own private key, so every new APK installs over the previous one. Otherwise the standard
// Android debug key of the build machine is used. No key material is stored in this repository.
val envKeystore: String? = System.getenv("AIO_KEYSTORE_FILE")?.takeIf { it.isNotBlank() && file(it).exists() }

android {
    namespace = "com.aio.tracker"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.aio.tracker"
        minSdk = 26
        targetSdk = 35
        versionCode = (System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull() ?: 1)
        versionName = "1.0." + (System.getenv("GITHUB_RUN_NUMBER") ?: "0")
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        if (envKeystore != null) {
            create("own") {
                storeFile = file(envKeystore)
                storePassword = System.getenv("AIO_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("AIO_KEY_ALIAS")
                keyPassword = System.getenv("AIO_KEY_PASSWORD")
            }
        }
    }
    val appSigning = if (envKeystore != null) signingConfigs.getByName("own") else signingConfigs.getByName("debug")

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = appSigning
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
            signingConfig = appSigning
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
        freeCompilerArgs += listOf(
            "-opt-in=androidx.compose.material3.ExperimentalMaterial3Api",
            "-opt-in=androidx.compose.foundation.ExperimentalFoundationApi",
            "-opt-in=androidx.compose.foundation.layout.ExperimentalLayoutApi",
        )
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    }
    testOptions {
        unitTests.isIncludeAndroidResources = true
        unitTests.all {
            it.testLogging {
                events("passed", "failed", "skipped")
                exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
            }
        }
    }
    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

